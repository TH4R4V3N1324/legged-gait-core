#include "gait_core/robots/explorer.hpp"

#include <limits>

namespace gait_core::explorer {

static_assert(kMaxLegs >= NUM_LEGS, "explorer has 6 legs: GAIT_CORE_MAX_LEGS must be at least 6");

namespace {

/**
 * @brief Helper to make a revolute joint definition
 * @param origin The joint's position relative to the previous joint (or the leg frame origin),
 *        at zero angles (m)
 * @param axis The joint's unit axis, in the leg frame at zero angles
 * @param lower The joint's lower limit (rad)
 * @param upper The joint's upper limit (rad)
 * @param maxVelocity The fastest its servo may turn (rad/s); infinity for GaitParams::max_joint_speed
*/
JointDefinition revolute(const Vec3& origin, const Vec3& axis, double lower, double upper,
                         Scalar maxVelocity = std::numeric_limits<Scalar>::infinity()) {
    return {origin, axis, static_cast<Scalar>(lower), static_cast<Scalar>(upper), maxVelocity};
}

/**
 * @brief Helper to make a Vec3 from doubles
 * @param x The x component
 * @param y The y component
 * @param z The z component
*/
Vec3 v(double x, double y, double z) {
    return Vec3(static_cast<Scalar>(x), static_cast<Scalar>(y), static_cast<Scalar>(z));
}

}  // namespace

RobotDefinition robot() {
    RobotDefinition g{};
    g.numLegs = NUM_LEGS;

    // The femur and tibia ranges match femur_lower/upper and tibia_lower/upper in the URDF (from the
    // CAD meshes); the coxa keeps +-1.4 rad until its range is worked out
    // Speed limits: each servo's no-load top speed on a 3S pack (11.1 V nominal). The URDF's are the
    // 12 V figures (4.7 and 7.9 rad/s), which the battery can't reach.
    constexpr Scalar ST3215_SPEED = Scalar(4.36);   // rad/s, coxa and tibia (0.222 s/60 deg at 12 V)
    constexpr Scalar STS3250_SPEED = Scalar(7.28);  // rad/s, femur (0.133 s/60 deg at 12 V)
    const JointDefinition coxa = revolute(v(0, 0, 0), v(0, 0, 1), -1.4, 1.4, ST3215_SPEED);
    const JointDefinition femur = revolute(v(0.063, 0, 0), v(0, 1, 0), -1.6, 1.4, STS3250_SPEED);    // + lowers the foot
    const JointDefinition tibia = revolute(v(0.100, 0, 0), v(0, 1, 0), -0.78, 2.63, ST3215_SPEED);  // + folds the knee

    // Coxa joint yaw (rad) and position (m), matching the URDF: the middle legs 0.11836 m out
    // to the side, the corner legs at 45 degrees from (0.11916, 0.08952) on the slimmer body
    const Scalar m  = static_cast<Scalar>(0.11836);
    const Scalar cx = static_cast<Scalar>(0.11916);
    const Scalar cy = static_cast<Scalar>(0.08952);
    const Vec3 foot_offset = v(0.186, 0, 0);

    // Masses and centres of mass from the CAD, as hexapod.inertials.xacro in hexapod-ros2 has them
    // (generated by scripts/mass_properties.py from Hexapod_V6.1.step; printed parts at 60% of solid
    // until weighed). Whole robot 3.323 kg, two thirds of it in the legs. The left and right links
    // mirror each other in y.
    g.bodyMass = static_cast<Scalar>(1.1082);
    g.centreOfMass = v(-0.00433, 0.00009, 0.00993);

    auto leg = [&](Scalar yaw, const Vec3& coxaPosition) {
        LegDefinition def{{yaw, coxaPosition}, 3, {coxa, femur, tibia}, foot_offset};
        def.solver = LegSolver::YawPitchPitch;  // coxa about z, femur and tibia about y: exact and fast
        const double side = yaw > 0 ? 1 : -1;   // left legs face +y
        def.joints[0].mass = static_cast<Scalar>(0.0934);
        def.joints[0].centreOfMass = v(0.02018, side * 0.00006, -0.00074);
        def.joints[1].mass = static_cast<Scalar>(0.1724);
        def.joints[1].centreOfMass = v(0.05000, side * 0.00002, 0);
        def.joints[2].mass = static_cast<Scalar>(0.1034);
        def.joints[2].centreOfMass = v(0.07831, 0, 0.01279);
        return def;
    };

    g.legs[LEG_FRONT_RIGHT]  = leg(-kPi / 4, Vec3(cx, -cy, 0));
    g.legs[LEG_MIDDLE_RIGHT] = leg(-kPi / 2, Vec3(0, -m, 0));
    g.legs[LEG_REAR_RIGHT]   = leg(-3 * kPi / 4, Vec3(-cx, -cy, 0));
    g.legs[LEG_REAR_LEFT]    = leg(3 * kPi / 4, Vec3(-cx, cy, 0));
    g.legs[LEG_MIDDLE_LEFT]  = leg(kPi / 2, Vec3(0, m, 0));
    g.legs[LEG_FRONT_LEFT]   = leg(kPi / 4, Vec3(cx, cy, 0));

    // Each foot straight out from its coxa (so the corner feet
    // sit at 45 degrees), 0.177 m out and 0.134 m below the hips
    g.standReach  = static_cast<Scalar>(0.177);
    g.standHeight = static_cast<Scalar>(-0.134);

    g.maxStride = static_cast<Scalar>(0.07);

    // Indexed by the Gait names, which controllers and the ROS node use as gait ids
    g.numGaits = NUM_GAITS;
    // Two alternating tripods, each stable on its own
    g.gaits[GAIT_TRIPOD] = GaitPattern::fromGroups("tripod", {
        {LEG_FRONT_RIGHT, LEG_REAR_RIGHT, LEG_MIDDLE_LEFT},
        {LEG_MIDDLE_RIGHT, LEG_REAR_LEFT, LEG_FRONT_LEFT},
    });
    // Two legs at a time, one from each side
    g.gaits[GAIT_RIPPLE] = GaitPattern::fromGroups("ripple", {
        {LEG_REAR_RIGHT, LEG_FRONT_LEFT},
        {LEG_MIDDLE_RIGHT, LEG_REAR_LEFT},
        {LEG_FRONT_RIGHT, LEG_MIDDLE_LEFT},
    });
    // One leg at a time: the right side rear to front, then the left side rear to front
    g.gaits[GAIT_WAVE] = GaitPattern::fromGroups("wave", {
        {LEG_REAR_RIGHT}, {LEG_MIDDLE_RIGHT}, {LEG_FRONT_RIGHT},
        {LEG_REAR_LEFT}, {LEG_MIDDLE_LEFT}, {LEG_FRONT_LEFT},
    });
    return g;
}

}  // namespace gait_core::explorer
